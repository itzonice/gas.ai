// Combines every migration into a few files for the Supabase SQL Editor, for setting up a
// hosted project from a browser without the CLI: supabase/setup/part-N.sql. Each part also
// records its migrations in the CLI's history table, so a later `supabase db push` skips them.
// Run: node scripts/build-setup-sql.mjs (rerun after adding a migration).
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const out = new URL("../supabase/setup/", import.meta.url);
const MAX = 90_000;
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = [[]];
let size = 0;
for (const f of files) {
  const sql = readFileSync(new URL(f, dir), "utf8");
  if (size + sql.length > MAX && parts.at(-1).length) {
    parts.push([]);
    size = 0;
  }
  parts.at(-1).push({ f, sql });
  size += sql.length;
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
parts.forEach((part, i) => {
  const n = i + 1;
  const lines = [
    `-- StudyPulse database setup, part ${n} of ${parts.length}. GENERATED by`,
    "-- scripts/build-setup-sql.mjs; do not edit. Paste into the Supabase SQL Editor and Run,",
    `-- after part ${n - 1 || "(none: this is the first)"}.`,
    "",
  ];
  for (const { f, sql } of part) lines.push(`-- ==== ${f}`, sql.trimEnd(), "");
  lines.push(
    "-- Record these migrations so the Supabase CLI knows they're applied.",
    "create schema if not exists supabase_migrations;",
    "create table if not exists supabase_migrations.schema_migrations (",
    "  version text primary key, statements text[], name text);",
    "insert into supabase_migrations.schema_migrations (version, name) values",
    part
      .map(({ f }) => {
        const [version, ...rest] = f.replace(/\.sql$/, "").split("_");
        return `  ('${version}', '${rest.join("_")}')`;
      })
      .join(",\n"),
    "on conflict (version) do nothing;",
    `select 'StudyPulse setup part ${n} of ${parts.length} done' as result;`,
    "",
  );
  writeFileSync(new URL(`part-${n}.sql`, out), lines.join("\n"));
});
console.log(`wrote ${parts.length} parts for ${files.length} migrations`);
